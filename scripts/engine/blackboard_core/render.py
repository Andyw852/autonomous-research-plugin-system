def counts_to(hid: str, evidence: dict) -> str:
    c = _evidence_counts(evidence, hid)
    return (
        f"support {c['support']} / challenge {c['challenge']} / mixed {c['mixed']} "
        f"/ pending {c['pending']} / rejected {c['rejected']}"
    )


def _evidence_counts(evidence: dict, hypothesis_id: str | None) -> dict:
    counts = {"support": 0, "challenge": 0, "mixed": 0, "pending": 0, "rejected": 0}
    for e in evidence.values():
        if e.get("hypothesis_id") != hypothesis_id:
            continue
        verdict = e.get("verdict")
        if verdict == "rejected":
            counts["rejected"] += 1
        elif verdict != "accepted":
            counts["pending"] += 1
        else:
            direction = e.get("direction") or "support"
            counts[direction if direction in counts else "mixed"] += 1
    return counts


