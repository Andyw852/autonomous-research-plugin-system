def render_task(run_root: Path, model: dict, tid: str, out_dir: Path) -> Path:
    t = model["tasks"][tid]
    mission_id = None
    for ev in model["timeline"]:
        if ev.get("task_id") == tid:
            mission_id = ev.get("mission_id") or mission_id
    mission_id = mission_id or ""
    tdir = out_dir / "missions" / mission_id / "tasks"
    tdir.mkdir(parents=True, exist_ok=True)
    nav = '<a href="../../index.html">Mission</a>'
    header = (
        f'<p><code>{_esc(tid)}</code> · role {_badge(_esc(t.get("role") or "—"), "b-neu")}'
        f' · start {_esc((t.get("start") or "")[:19])} · end {_esc((t.get("end") or "")[:19])}</p>'
    )
    nodes = []
    for ev in t["events"]:
        content = ev.get("content") or {}
        details = []
        for key, label in (
            ("tool_name", "Tool"), ("command", "Command"), ("exit_code", "Exit code"),
            ("wall_seconds", "Wall seconds"), ("status", "Status"), ("attempt_index", "Attempt"),
            ("input_summary", "Input"), ("output_summary", "Output"), ("error", "Error"),
            ("progress_ts", "Recorded at"),
        ):
            v = content.get(key)
            if v is not None:
                details.append(f"<dt>{label}</dt><dd><code>{_esc(v)}</code></dd>")
        arts = content.get("artifact_files") or []
        if arts:
            details.append("<dt>Artifacts</dt><dd>"
                           + ", ".join(f"<code>{_esc(a)}</code>" for a in arts) + "</dd>")
        dl = f"<dl>{''.join(details)}</dl>" if details else ""
        nodes.append(
            f'<div class="tl-item"><span class="tl-time">{_esc((ev.get("created_at") or "")[:19])}</span> '
            f'{_badge(_esc(ev.get("kind") or ""), "b-neu")} '
            f'<strong>{_esc(ev.get("summary") or "")}</strong>{dl}</div>'
        )
    body = header + "<h2>Task trajectory (%d nodes)</h2><div class=\"timeline\">" % len(nodes) + "".join(nodes) + "</div>"
    path = tdir / f"{tid}.html"
    path.write_text(_page(f"Task Trajectory · {tid}", body, nav), encoding="utf-8")
    return path


