def render_experience(run_root: Path, out_dir: Path) -> Path:
    """Write blackboard/experience.html: engineering knowledge, grouped by category."""
    from events import experience_list

    entries = experience_list(run_root)
    nav = '<a href="index.html">Overview</a> <a href="timeline.html">Timeline</a>'
    intro = (
        "<p class=\"muted\">Engineering knowledge only (environment, tools, scripts, "
        "workflow, pitfalls) - never chemical conclusions; those live in the evidence "
        "pipeline.</p>"
    )
    if not entries:
        body = "<h2>Experience library</h2>" + intro + "<p class=\"muted\">No entries yet.</p>"
        path = out_dir / "experience.html"
        path.write_text(_page("Experience Library", body, nav), encoding="utf-8")
        return path

    groups: dict[str, list] = {}
    for e in entries:
        groups.setdefault(e.get("category") or "other", []).append(e)
    blocks = []
    for cat in sorted(groups):
        cards = ""
        for e in groups[cat]:
            src = []
            if e.get("source_role"):
                src.append(f"role {_esc(e['source_role'])}")
            if e.get("source_task"):
                src.append(f"<code>{_esc(e['source_task'])}</code>")
            cards += (
                f'<div class="card"><span class="tl-time">{_esc((e.get("created_at") or "")[:19])}</span> '
                f'{_badge(_esc(e.get("category") or ""), "b-neu")} '
                f'<strong>{_esc(e.get("summary") or "")}</strong>'
                + (f'<p>{_esc(e.get("detail") or "")}</p>' if e.get("detail") else "")
                + (f'<p class="muted">Source: {" · ".join(src)}</p>' if src else "")
                + "</div>"
            )
        label = _EXPERIENCE_LABELS.get(cat, cat)
        blocks.append(f"<h2>{_esc(label)} ({len(groups[cat])})</h2>{cards}")
    body = "<h2>Experience library</h2>" + intro + "".join(blocks)
    path = out_dir / "experience.html"
    path.write_text(_page("Experience Library", body, nav), encoding="utf-8")
    return path


