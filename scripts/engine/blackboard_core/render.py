def _task_status(t: dict) -> str:
    """Derive the task status from its trace events."""
    kinds = {ev.get("kind") for ev in t["events"]}
    if "task_end" in kinds:
        return "completed"
    if "delivery_received" in kinds:
        return "delivered"
    if "attempt_start" in kinds or "tool_run" in kinds:
        return "in_progress"
    if "task_start" in kinds:
        return "started"
    return "assigned"


def _task_counts(t: dict) -> dict:
    kinds = [ev.get("kind") for ev in t["events"]]
    return {
        "attempts": kinds.count("attempt_start"),
        "tool_runs": kinds.count("tool_run"),
        "nodes": len(t["events"]),
    }


def render_task_board(run_root: Path, model: dict, mission_id: str, out_dir: Path) -> Path:
    """Write missions/<MIS>/tasks/index.html: per-task cards derived from traces."""
    tdir = out_dir / "missions" / mission_id / "tasks"
    tdir.mkdir(parents=True, exist_ok=True)
    nav = (
        '<a href="../../index.html">Mission</a> '
        '<a href="../../timeline.html">Timeline</a>'
    )
    status_cls = {
        "completed": "b-ok", "delivered": "b-wait", "in_progress": "b-h",
        "started": "b-neu", "assigned": "b-p",
    }
    cards = []
    for tid, t in sorted(model["tasks"].items()):
        in_mission = any(
            ev.get("mission_id") == mission_id
            for ev in model["timeline"]
            if ev.get("task_id") == tid
        )
        if not in_mission:
            continue
        status = _task_status(t)
        counts = _task_counts(t)
        cards.append(
            f'<div class="card"><strong><code>{_esc(tid)}</code></strong> '
            f'{_badge(_esc(t.get("role") or "—"), "b-neu")} '
            f'{_badge(status, status_cls.get(status, "b-p"))}'
            f'<p class="muted">attempts {counts["attempts"]} · tool runs {counts["tool_runs"]} · '
            f'{counts["nodes"]} trace nodes · start {_esc((t.get("start") or "")[:19])}'
            f' · end {_esc((t.get("end") or "")[:19])}</p>'
            f'<a href="{_esc(tid)}.html">View trace →</a></div>'
        )
    body = (
        f"<h2>Task board</h2>"
        + ("".join(cards) if cards else "<p class=\"muted\">No tasks yet.</p>")
    )
    path = tdir / "index.html"
    path.write_text(_page(f"Task Board · {mission_id}", body, nav), encoding="utf-8")
    return path


