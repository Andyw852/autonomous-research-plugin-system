def _render_chain(model: dict, mission_id: str) -> str:
    """Render replies_to chains as a continuous exchange."""
    by_id = {ev["id"]: ev for ev in model["timeline"]}
    evs = [ev for ev in model["timeline"] if ev.get("mission_id") == mission_id]
    linked = set()
    blocks: list[str] = []
    for ev in evs:
        rid = ev.get("replies_to")
        if rid and rid in by_id:
            prev = by_id[rid]
            linked.update({ev["id"], rid})
            blocks.append(
                f'<div class="chain">'
                f'<span class="tl-time">{_esc((prev.get("created_at") or "")[:19])}</span> '
                f'{_badge(_esc(prev.get("role") or "—"), "b-neu")} {_esc(prev.get("summary") or "")}'
                f'<br>↳ <span class="tl-time">{_esc((ev.get("created_at") or "")[:19])}</span> '
                f'{_badge(_esc(ev.get("role") or "—"), "b-neu")} {_esc(ev.get("summary") or "")}'
                f'</div>'
            )
    unlinked = [ev for ev in evs if ev["id"] not in linked and ev.get("type") not in {"checkpoint"}]
    unlinked_html = "".join(
        f'<div class="chain">{_badge(_esc(ev.get("role") or "—"), "b-neu")} {_esc(ev.get("summary") or "")}</div>'
        for ev in unlinked[-8:]
    )
    return "".join(blocks) + unlinked_html or "<p class=\"muted\">No exchange recorded yet.</p>"


