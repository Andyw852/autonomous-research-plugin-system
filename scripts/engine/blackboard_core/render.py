def render_all(run_root: Path, checkpoint: bool = False) -> list[str]:
    """Rebuild all views. Return the list of written file paths relative to the run root."""
    from events import write_checkpoint, validate_log

    errors = validate_log(run_root)
    if errors:
        raise ValueError("Log validation failed; refusing to render:\n  - " + "\n  - ".join(errors))

    model = build_model(run_root)
    out_dir = run_root / "blackboard"
    out_dir.mkdir(parents=True, exist_ok=True)

    written: list[str] = []
    written.append(render_campaign(run_root, model, out_dir)[0])
    written.append("blackboard/README.md")
    written.append(str(render_global_timeline(run_root, model, out_dir).relative_to(run_root)))
    written.append(str(render_experience(run_root, out_dir).relative_to(run_root)))
    written.append(str(render_research_snapshot(run_root, model, out_dir).relative_to(run_root)))
    written += render_directives_pages(run_root, out_dir)

    for mission_id in model["missions"]:
        written.append(str(render_mission(run_root, model, mission_id, out_dir).relative_to(run_root)))
        written.append(f"blackboard/missions/{mission_id}/report.md")
        written.append(f"blackboard/missions/{mission_id}/timeline.html")
        written.append(str(render_task_board(run_root, model, mission_id, out_dir).relative_to(run_root)))

    for hid in model["hypotheses"]:
        h = model["hypotheses"][hid]
        mid = h.get("mission_id") or model.get("last_mission_id") or ""
        written.append(str(render_hypothesis(run_root, model, hid, out_dir, mid).relative_to(run_root)))
        written.append(f"blackboard/missions/{mid}/hypotheses/{hid}/{hid}.md")

    for eid in model["evidence"]:
        written.append(str(render_evidence(run_root, model, eid, out_dir).relative_to(run_root)))
        written.append(f"blackboard/missions/{model['evidence'][eid].get('mission_id') or ''}/evidence/{eid}/{eid}.md")

    for tid in model["tasks"]:
        written.append(str(render_task(run_root, model, tid, out_dir).relative_to(run_root)))

    if checkpoint:
        ck = write_checkpoint(run_root, model)
        written.append(f"blackboard/checkpoints/{ck['id']}.json")

    return written


def _cli() -> int:
    import argparse

    parser = argparse.ArgumentParser(description="Rebuild all blackboard views")
    parser.add_argument("run_root", help="run root directory")
    parser.add_argument("--checkpoint", action="store_true", help="also write a checkpoint after rendering")
    args = parser.parse_args()
    try:
        written = render_all(Path(args.run_root).resolve(), checkpoint=args.checkpoint)
    except ValueError as exc:
        print(str(exc), file=sys.stderr)
        return 1
    print(f"Wrote {len(written)} files:")
    for w in written:
        print("  " + w)
    return 0


if __name__ == "__main__":
    sys.exit(_cli())