def _esc(text: object) -> str:
    return html.escape(str(text if text is not None else ""))


def _page(title: str, body: str, crumbs: str = "") -> str:
    return (
        "<!doctype html>\n<html lang=\"en\">\n<head>\n"
        "<meta charset=\"utf-8\">\n<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">\n"
        f"<title>{_esc(title)}</title>\n<style>{_CSS}</style>\n</head>\n<body>\n"
        f"<header><h1>{_esc(title)}</h1></header>\n"
        f"<nav aria-label=\"Navigation\">{crumbs}</nav>\n<main>\n{body}\n</main>\n"
        "<footer class=\"footer\">Derived view generated by render.py; the authoritative "
        "sources are timeline.jsonl and traces.jsonl at the run root</footer>\n"
        "</body></html>\n"
    )


def _badge(text: str, cls: str = "b-neu") -> str:
    return f'<span class="badge {cls}">{_esc(text)}</span>'


def _assessment_badge(assessment: str) -> str:
    table = {
        "supported": ("Supported", "b-s"),
        "weakened": ("Weakened", "b-w"),
        "mixed": ("Mixed", "b-m"),
        "refuted": ("Refuted", "b-r"),
        "unassessed": ("Unassessed", "b-p"),
    }
    label, cls = table.get(assessment, (assessment, "b-p"))
    return _badge(label, cls)


def _verdict_badge(verdict: str | None) -> str:
    if verdict == "accepted":
        return _badge("Accepted", "b-ok")
    if verdict == "rejected":
        return _badge("Rejected", "b-bad")
    if verdict == "needs_more_work":
        return _badge("Needs more work", "b-wait")
    return _badge("Pending review", "b-p")


def _mission_verdict_badge(verdict: str | None) -> str:
    cls = {"converged": "b-ok", "blocked": "b-bad", "not_testable": "b-bad"}.get(verdict or "", "b-wait")
    return _badge(_esc(verdict or "no verdict"), cls)


def _law_ledger(content: dict) -> dict:
    ledger = content.get("law_quality_ledger") or {}
    return ledger if isinstance(ledger, dict) else {}


def _law_ledger_html(content: dict) -> str:
    ledger = _law_ledger(content)
    if not ledger:
        return ""
    criteria = ledger.get("criteria") or {}
    criteria_html = "".join(
        f"<li>{_esc(str(k))}: {_esc(str(v))}</li>"
        for k, v in criteria.items()
    ) if isinstance(criteria, dict) else ""
    gaps = "".join(f"<li>{_esc(str(g))}</li>" for g in ledger.get("gaps") or [])
    return (
        f'<p><strong>Law candidate:</strong> {_esc(ledger.get("law_candidate") or "")}</p>'
        f'<p><strong>Law maturity:</strong> {_esc(ledger.get("maturity") or "?")}</p>'
        + (f'<p><strong>Law-quality criteria:</strong></p><ul>{criteria_html}</ul>' if criteria_html else "")
        + (f'<p><strong>Law-quality gaps:</strong></p><ul>{gaps}</ul>' if gaps else "")
    )


def _law_ledger_md(content: dict) -> list[str]:
    ledger = _law_ledger(content)
    if not ledger:
        return []
    lines = [
        f"  - Law candidate: {ledger.get('law_candidate', '')}",
        f"  - Law maturity: {ledger.get('maturity', '?')}",
    ]
    criteria = ledger.get("criteria") or {}
    if isinstance(criteria, dict):
        lines.extend(f"    - {key}: {value}" for key, value in criteria.items())
    lines.extend(f"  - Law gap: {gap}" for gap in ledger.get("gaps") or [])
    return lines


