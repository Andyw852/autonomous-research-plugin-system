def _md_inline(text: str) -> str:
    t = html.escape(text)
    t = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", t)
    t = re.sub(r"`([^`]+)`", r"<code>\1</code>", t)
    return t


def _md_simple(text: str) -> str:
    """Minimal, dependency-free Markdown -> HTML for the directive narratives."""
    out: list[str] = []
    para: list[str] = []
    list_open = False

    def flush() -> None:
        nonlocal list_open
        if list_open:
            out.append("</ul>")
            list_open = False
        if para:
            out.append("<p>" + " ".join(para) + "</p>")
            para.clear()

    for raw in text.splitlines():
        line = raw.strip()
        if not line:
            flush()
        elif line.startswith("### "):
            flush(); out.append(f"<h4>{_esc(line[4:])}</h4>")
        elif line.startswith("## "):
            flush(); out.append(f"<h3>{_esc(line[3:])}</h3>")
        elif line.startswith("# "):
            flush(); out.append(f"<h2>{_esc(line[2:])}</h2>")
        elif line.startswith("- ") or line.startswith("* "):
            if not list_open:
                flush(); out.append("<ul>")
                list_open = True
            out.append(f"<li>{_md_inline(line[2:])}</li>")
        else:
            if list_open:
                out.append("</ul>")
                list_open = False
            para.append(_md_inline(line))
    flush()
    return "".join(out)


def _scan_directives(run_root: Path) -> list[dict]:
    """Scan blackboard/directives (including consumed/) and return per-round info."""
    ddir = run_root / "blackboard" / "directives"
    if not ddir.is_dir():
        return []
    groups: dict[str, dict] = {}
    for path in sorted(ddir.rglob("round-*")):
        if not path.is_dir():
            continue
        g = groups.setdefault(path.name, {"round": path.name, "proposal": {}, "decision": {}})
        for key in ("proposal", "decision"):
            jp = path / f"{key}.json"
            if jp.is_file():
                try:
                    g[key] = json.loads(jp.read_text(encoding="utf-8"))
                except (ValueError, OSError):
                    g[key] = {}
            mp = path / f"{key}.md"
            if mp.is_file():
                g[key]["_md"] = mp.read_text(encoding="utf-8")
    return [groups[k] for k in sorted(groups)]


def _directive_payload(d: dict) -> dict:
    """Return the meaningful payload of a directive json (unwrap the 'mission' key)."""
    if isinstance(d.get("mission"), dict):
        return d["mission"]
    return d


def _directive_field_rows(data: dict) -> str:
    rows = []
    for key, label in (
        ("research_question", "Research question"),
        ("expected_knowledge_gain", "Expected knowledge gain"),
        ("narrowing_rationale", "Narrowing rationale"),
    ):
        v = data.get(key)
        if v:
            rows.append(f"<dt>{label}</dt><dd>{_esc(v)}</dd>")
    for key, label in (
        ("hypothesis_directions", "Hypothesis directions"),
        ("scope", "Scope"),
        ("non_goals", "Non-goals"),
        ("boundary_extension_targets", "Boundary extension targets"),
        ("exit_conditions", "Exit conditions"),
    ):
        v = data.get(key)
        if v:
            items = "".join(f"<li>{_esc(i)}</li>" for i in v) if isinstance(v, list) else f"<li>{_esc(v)}</li>"
            rows.append(f"<dt>{label}</dt><dd><ul>{items}</ul></dd>")
    return f"<dl>{''.join(rows)}</dl>" if rows else ""


def render_directive_page(run_root: Path, out_dir: Path, round_name: str, data: dict, kind: str) -> Path | None:
    """Write blackboard/directives/<round>/<kind>.html for one directive. Return its path."""
    payload = _directive_payload(data)
    if not payload and not data.get("_md"):
        return None
    ddir = out_dir / "directives" / round_name
    ddir.mkdir(parents=True, exist_ok=True)
    nav = (
        '<a href="../../index.html">Overview</a> '
        '<a href="../../timeline.html">Timeline</a> '
        f'<a href="{_esc(kind)}.md">Raw {_esc(kind)}.md</a>'
    )
    md_html = f"<h2>Detailed narrative</h2>{_md_simple(data.get('_md') or '')}" if data.get("_md") else ""
    body = f"<h2>{_esc(kind.title())} fields</h2><div class=\"card\">{_directive_field_rows(payload)}</div>{md_html}"
    path = ddir / f"{kind}.html"
    path.write_text(_page(f"Director {kind.title()} · {round_name}", body, nav), encoding="utf-8")
    return path


def _directives_index_html(run_root: Path) -> str:
    """HTML block for the campaign overview: one card per round with a proposal/decision."""
    rounds = _scan_directives(run_root)
    if not rounds:
        return "<h2>Director directives (0)</h2><p class=\"muted\">No directives yet.</p>"
    cards = []
    for g in rounds:
        rname = g["round"]
        prop, dec = g["proposal"], g["decision"]
        prop_payload = _directive_payload(prop)
        bits = []
        if prop_payload or prop.get("_md"):
            name = prop_payload.get("name") or "Mission proposal"
            question = prop_payload.get("research_question") or prop.get("summary") or ""
            bits.append(
                f'<p><strong>Proposal:</strong> {_esc(name)}</p>'
                + (f'<p class="muted">{_esc(question)}</p>' if question else "")
                + f'<a href="directives/{_esc(rname)}/proposal.html">Proposal details →</a>'
            )
        if dec or dec.get("_md"):
            rec = dec.get("recommendation") or dec.get("directive_type") or "decision"
            rationale = dec.get("rationale") or dec.get("summary") or ""
            bits.append(
                f'<p><strong>Decision:</strong> {_badge(_esc(rec), "b-neu")}</p>'
                + (f'<p class="muted">{_esc(rationale)}</p>' if rationale else "")
                + f'<a href="directives/{_esc(rname)}/decision.html">Decision details →</a>'
            )
        if bits:
            cards.append(f'<div class="card"><strong>Round <code>{_esc(rname)}</code></strong>' + "".join(bits) + "</div>")
    return f"<h2>Director directives ({len(rounds)})</h2>" + ("".join(cards) if cards else "<p class=\"muted\">No directives yet.</p>")


def render_directives_pages(run_root: Path, out_dir: Path) -> list[str]:
    """Write the per-round directive detail pages. Return relative written paths."""
    written = []
    for g in _scan_directives(run_root):
        rname = g["round"]
        for kind in ("proposal", "decision"):
            p = render_directive_page(run_root, out_dir, rname, g[kind], kind)
            if p:
                written.append(str(p.relative_to(run_root)))
    return written


